//! Writes the parameter registry and wire codes as TypeScript, so the UI binds to the
//! exact same table the engine uses. See `bin/gen_types.rs`.

use crate::engine::{cmd, out};
use crate::params::*;
use std::fmt::Write;


fn spec_ts(group: &str, s: &ParamSpec, index: usize) -> String {
    let detents: Vec<String> = s.detents.iter().map(|d| fmt(*d)).collect();
    format!(
        "{{ id: \"{group}.{id}\", key: \"{id}\", label: \"{label}\", bank: \"{bank}\", index: {index}, min: {min}, max: {max}, default: {def}, unit: \"{unit}\", curve: \"{curve}\", smoothMs: {sm}, detents: [{det}] }}",
        id = s.id,
        label = s.label,
        bank = s.bank.name(),
        min = fmt(s.min),
        max = fmt(s.max),
        def = fmt(s.default),
        unit = s.unit.name(),
        curve = s.curve.name(),
        sm = fmt(s.smooth_ms),
        det = detents.join(", "),
    )
}

fn fmt(v: f32) -> String {
    if v.is_infinite() {
        return if v < 0.0 { "-Infinity".into() } else { "Infinity".into() };
    }
    let s = format!("{v}");
    if s.contains('.') || s.contains('e') { s } else { format!("{s}") }
}

pub fn typescript() -> String {
    let mut o = String::new();
    o.push_str("// Generated by engine/src/bin/gen_types.rs. Do not edit by hand.\n");
    o.push_str("// Run: npm run engine:types (from artifacts/ccd-school)\n\n");

    o.push_str("export type Bank = \"sound\" | \"eq\" | \"fx\" | \"mix\" | \"shift\";\n");
    o.push_str("export type Unit = \"none\" | \"hz\" | \"db\" | \"pct\" | \"ms\" | \"st\" | \"pan\";\n");
    o.push_str("export type Curve = \"lin\" | \"exp\" | \"fader\";\n");
    o.push_str("export type ParamSpec = { id: string; key: string; label: string; bank: Bank; index: number; min: number; max: number; default: number; unit: Unit; curve: Curve; smoothMs: number; detents: number[] };\n\n");

    writeln!(o, "export const INSTRUMENT_BASE = {INSTRUMENT_BASE};").unwrap();
    writeln!(o, "export const MAX_PARAMS = {MAX_PARAMS};").unwrap();
    writeln!(o, "export const FADER_UNITY = {};", fmt(FADER_UNITY)).unwrap();
    writeln!(o, "export const FADER_MIN_DB = {};", fmt(FADER_MIN_DB)).unwrap();
    writeln!(o, "export const FADER_MAX_DB = {};\n", fmt(FADER_MAX_DB)).unwrap();

    o.push_str("export const LAYER_PARAMS = [\n");
    for (i, s) in LAYER_PARAMS.iter().enumerate() {
        let (group, short) = s.id.split_once('.').unwrap();
        let s2 = ParamSpec { id: short, ..*s };
        writeln!(o, "  {},", spec_ts(group, &s2, i)).unwrap();
    }
    o.push_str("] as const satisfies readonly ParamSpec[];\n\n");

    o.push_str("export const BASS_PARAMS = [\n");
    for (i, s) in BASS_PARAMS.iter().enumerate() {
        writeln!(o, "  {},", spec_ts("bass", s, INSTRUMENT_BASE + i)).unwrap();
    }
    o.push_str("] as const satisfies readonly ParamSpec[];\n\n");

    o.push_str("/** Per pad. Wire index = INSTRUMENT_BASE + pad * DRUM_PAD_PARAMS.length + index. */\n");
    o.push_str("export const DRUM_PAD_PARAMS = [\n");
    for (i, s) in DRUM_PAD_PARAMS.iter().enumerate() {
        writeln!(o, "  {},", spec_ts("drums.pad", s, i)).unwrap();
    }
    o.push_str("] as const satisfies readonly ParamSpec[];\n\n");

    o.push_str("/** Rack-wide drum knobs. Wire index = INSTRUMENT_BASE + DRUM_RACK_BASE + index. */\n");
    o.push_str("export const DRUM_RACK_PARAMS = [\n");
    for (i, s) in DRUM_RACK_PARAMS.iter().enumerate() {
        writeln!(o, "  {},", spec_ts("drums", s, INSTRUMENT_BASE + DRUM_RACK_BASE + i)).unwrap();
    }
    o.push_str("] as const satisfies readonly ParamSpec[];\n");
    writeln!(o, "export const DRUM_RACK_BASE = {DRUM_RACK_BASE};\n").unwrap();

    o.push_str("/** Per pad, second page. Wire index = INSTRUMENT_BASE + DRUM_PAD2_BASE + pad * DRUM_PAD2_STRIDE + index. */\n");
    o.push_str("export const DRUM_PAD2_PARAMS = [\n");
    for (i, s) in DRUM_PAD2_PARAMS.iter().enumerate() {
        writeln!(o, "  {},", spec_ts("drums.pad", s, i)).unwrap();
    }
    o.push_str("] as const satisfies readonly ParamSpec[];\n");
    writeln!(o, "export const DRUM_PAD2_BASE = {DRUM_PAD2_BASE};").unwrap();
    writeln!(o, "export const DRUM_PAD2_STRIDE = {DRUM_PAD2_STRIDE};\n").unwrap();

    for (name, group, table) in [("CHORD_PARAMS", "chords", CHORD_PARAMS), ("LEAD_PARAMS", "lead", LEAD_PARAMS), ("FX_PARAMS", "fx", FX_PARAMS), ("SAMPLER_PARAMS", "sampler", SAMPLER_PARAMS)] {
        writeln!(o, "export const {name} = [").unwrap();
        for (i, s) in table.iter().enumerate() {
            writeln!(o, "  {},", spec_ts(group, s, INSTRUMENT_BASE + i)).unwrap();
        }
        o.push_str("] as const satisfies readonly ParamSpec[];\n\n");
    }

    o.push_str("/** Master bus. Wire index for the MASTER command = position here. */\n");
    o.push_str("export const MASTER_PARAMS = [\n");
    for (i, s) in MASTER_PARAMS.iter().enumerate() {
        let (group, short) = s.id.split_once('.').unwrap();
        let s2 = ParamSpec { id: short, ..*s };
        writeln!(o, "  {},", spec_ts(group, &s2, i)).unwrap();
    }
    o.push_str("] as const satisfies readonly ParamSpec[];\n\n");

    let names: Vec<String> = DRUM_PAD_NAMES.iter().map(|n| format!("\"{n}\"")).collect();
    let notes: Vec<String> = DRUM_PAD_NOTES.iter().map(|n| n.to_string()).collect();
    writeln!(o, "export const DRUM_PAD_NAMES = [{}] as const;", names.join(", ")).unwrap();
    writeln!(o, "export const DRUM_PAD_NOTES = [{}] as const;", notes.join(", ")).unwrap();
    let fxn: Vec<String> = FX_NAMES.iter().map(|n| format!("\"{n}\"")).collect();
    writeln!(o, "export const FX_NAMES = [{}] as const;", fxn.join(", ")).unwrap();
    writeln!(o, "export const FX_NOTE_BASE = {FX_NOTE_BASE};").unwrap();
    writeln!(o, "export const FX_RISER_NOTE = {FX_RISER_NOTE};").unwrap();
    writeln!(o, "export const FX_IMPACT_NOTE = {FX_IMPACT_NOTE};").unwrap();
    writeln!(o, "export const SAMPLER_NOTE_BASE = {SAMPLER_NOTE_BASE};").unwrap();
    writeln!(o, "export const SAMPLER_ROOT = {SAMPLER_ROOT};\n").unwrap();

    o.push_str("export const INSTRUMENT = { none: 0, drums: 1, bass: 2, chords: 3, lead: 4, fx: 5, sampler: 6 } as const;\n");
    o.push_str("export type InstrumentName = keyof typeof INSTRUMENT;\n\n");

    o.push_str("export type LayerParamId = `${(typeof LAYER_PARAMS)[number][\"id\"]}`;\n");
    o.push_str("export type BassParamId = `${(typeof BASS_PARAMS)[number][\"id\"]}`;\n");
    o.push_str("export type DrumPadParamId = `${(typeof DRUM_PAD_PARAMS)[number][\"id\"]}`;\n");
    o.push_str("export type DrumRackParamId = `${(typeof DRUM_RACK_PARAMS)[number][\"id\"]}`;\n");
    o.push_str("export type DrumPad2ParamId = `${(typeof DRUM_PAD2_PARAMS)[number][\"id\"]}`;\n");
    o.push_str("export type ChordParamId = `${(typeof CHORD_PARAMS)[number][\"id\"]}`;\n");
    o.push_str("export type LeadParamId = `${(typeof LEAD_PARAMS)[number][\"id\"]}`;\n");
    o.push_str("export type FxParamId = `${(typeof FX_PARAMS)[number][\"id\"]}`;\n");
    o.push_str("export type SamplerParamId = `${(typeof SAMPLER_PARAMS)[number][\"id\"]}`;\n");
    o.push_str("export type ParamId = LayerParamId | BassParamId | DrumPadParamId | DrumRackParamId | DrumPad2ParamId | ChordParamId | LeadParamId | FxParamId | SamplerParamId;\n\n");

    writeln!(
        o,
        "export const CMD = {{ noteOn: {}, noteOff: {}, param: {}, instrument: {}, tempo: {}, loop: {}, play: {}, stop: {}, record: {}, recordOff: {}, evClear: {}, evAdd: {}, evCommit: {}, duck: {}, metronome: {}, allOff: {}, locate: {}, swing: {}, linkOff: {}, master: {}, snapshot: {}, compare: {}, analyse: {}, repeat: {}, mod: {}, trim: {} }} as const;",
        cmd::NOTE_ON, cmd::NOTE_OFF, cmd::PARAM, cmd::INSTRUMENT, cmd::TEMPO, cmd::LOOP, cmd::PLAY, cmd::STOP, cmd::RECORD, cmd::RECORD_OFF,
        cmd::EV_CLEAR, cmd::EV_ADD, cmd::EV_COMMIT, cmd::DUCK, cmd::METRONOME, cmd::ALL_OFF, cmd::LOCATE, cmd::SWING, cmd::LINK_OFF,
        cmd::MASTER, cmd::SNAPSHOT, cmd::COMPARE, cmd::ANALYSE, cmd::REPEAT, cmd::MOD, cmd::TRIM
    )
    .unwrap();
    writeln!(
        o,
        "export const OUT = {{ playedOn: {}, playedOff: {}, pos: {}, seqOn: {}, meter: {}, bands: {}, clash: {}, masterMeter: {}, loudness: {} }} as const;",
        out::PLAYED_ON, out::PLAYED_OFF, out::POS, out::SEQ_ON, out::METER, out::BANDS, out::CLASH, out::MASTER_METER, out::LOUDNESS
    )
    .unwrap();
    writeln!(o, "/** Clash fixes, as packed in a CLASH event's flags. */").unwrap();
    writeln!(o, "export const FIX = {{ duck: {}, eq: {}, pan: {}, none: {} }} as const;", crate::analysis::fix::DUCK, crate::analysis::fix::EQ, crate::analysis::fix::PAN, crate::analysis::fix::NONE).unwrap();
    writeln!(o, "/** Layer number the master's readings come with. */").unwrap();
    writeln!(o, "export const MASTER_LAYER = {};", crate::engine::MASTER_LAYER).unwrap();
    writeln!(o, "/** Fixed delay through the engine, in samples (2x stages and the limiter's look-ahead). */").unwrap();
    writeln!(o, "export const LATENCY_SAMPLES = {};", crate::engine::LATENCY).unwrap();
    writeln!(o, "export const CEILING_DB = {};", fmt(crate::master::CEILING_DB)).unwrap();
    writeln!(o, "/** Export loudness, integrated LUFS: streaming (the default) and loud, for club play. */").unwrap();
    writeln!(o, "export const EXPORT_LUFS = {};", fmt(crate::loudness::EXPORT_LUFS)).unwrap();
    writeln!(o, "export const EXPORT_LOUD_LUFS = {};", fmt(crate::loudness::EXPORT_LOUD_LUFS)).unwrap();
    let ratios: Vec<String> = crate::master::GLUE_RATIOS.iter().map(|r| fmt(*r)).collect();
    writeln!(o, "/** The glue's ratio switch steps. */").unwrap();
    writeln!(o, "export const GLUE_RATIOS = [{}] as const;", ratios.join(", ")).unwrap();
    writeln!(o, "export const MIX_PARAMS = {};", crate::engine::MIX_PARAMS).unwrap();
    writeln!(o, "/** Modulation: slots per layer and the sources (cmd mod: a slot, x amount, y wire param, z source). */").unwrap();
    writeln!(o, "export const MAX_MODS = {};", crate::engine::MAX_MODS).unwrap();
    writeln!(o, "export const MOD_SRC = {{ lfo: {}, env: {} }} as const;", crate::engine::MOD_LFO, crate::engine::MOD_ENV).unwrap();
    writeln!(o, "export const FLAG = {{ playing: {}, countIn: {}, recording: {}, link: {}, repeat: {} }} as const;", out::F_PLAYING, out::F_COUNT_IN, out::F_RECORDING, out::F_LINK, out::F_REPEAT).unwrap();
    writeln!(o, "export const OUT_EVENT_BYTES = {};\n", std::mem::size_of::<crate::engine::OutEv>()).unwrap();

    // Values from Rust for the TS curve tests, so both sides stay identical.
    o.push_str("/** Rust's own mapping at a few points, for the TypeScript tests. */\n");
    o.push_str("export const CURVE_VECTORS = [\n");
    let probes = [0.0f32, 0.1, 0.25, 0.5, 0.6, 0.75, 0.9, 1.0];
    for (group, s) in [("", &LAYER_PARAMS[L_LEVEL]), ("", &LAYER_PARAMS[L_PAN]), ("", &LAYER_PARAMS[L_EQ_CUT]), ("bass.", &BASS_PARAMS[B_CUTOFF]), ("bass.", &BASS_PARAMS[B_GLIDE])] {
        for n in probes {
            writeln!(o, "  {{ id: \"{group}{}\", n: {}, v: {} }},", s.id, fmt(n), fmt(s.to_value(n))).unwrap();
        }
    }
    o.push_str("] as const;\n");

    o
}

#[cfg(test)]
mod tests {
    #[test]
    fn committed_typescript_is_current() {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../artifacts/ccd-school/src/engine/params.gen.ts");
        let on_disk = std::fs::read_to_string(path).expect("run: npm run engine:types");
        assert!(on_disk == super::typescript(), "params.gen.ts is stale. Run: npm run engine:types");
    }
}
