//! 2x oversampling. Voices and saturators run at twice the rate, then a half-band
//! filter brings them back down with everything above the original Nyquist removed.
//!
//! The half-bands are polyphase IIR filters: two chains of first-order allpass
//! sections, one per phase (Valenzuela and Constantinides, "Digital signal processing
//! schemes for efficient interpolation and decimation", 1983; the same structure as
//! Laurent de Soras' HIIR). Compared with the 49-tap FIR they replace, they add 1 to
//! 1.5 samples per stage instead of 12, so the 2x path through a voice and its strip
//! is 5 samples (0.10 ms at 48 kHz) instead of 48 (1 ms).
//!
//! Their delay is not the same at every frequency (an IIR filter cannot be linear
//! phase). The coefficients are chosen so the delay at low and mid frequencies is a
//! whole or half sample, which lets the engine compensate it exactly, like a DAW's
//! delay compensation. Above about 10 kHz the filters lag by up to a few more samples,
//! which is how low-latency oversampling in commercial plugins behaves too.

use super::flush_denormal;

/// Delays at low frequencies, in base-rate samples. A decimator's output lines up
/// with the later sample of its pair, which takes half a sample off its delay.
pub const INTERP_DELAY: f64 = 1.5;
pub const DECIM_DELAY: f64 = 1.0;
/// Delay of the bass synth's decimator.
pub const BASS_DECIM_DELAY: f64 = 1.5;
/// Delay through a `Drive` (up then down). The strip has one and every drum pad has
/// one, so a drum hit leaves the engine 5 samples after it starts.
pub const DRIVE_DELAY: f64 = INTERP_DELAY + DECIM_DELAY;

/// Stage A: 6 coefficients, transition band 1/16 of the oversampled rate.
/// Stopband about -86 dB from 27 kHz (at 48 kHz in), flat to 21 kHz.
/// Generated by `design(6, 0.0625)`; the test below checks the table against it.
const COEFS_A: [f32; 6] = [0.052_904_929, 0.192_601_67, 0.376_506_4, 0.566_026_85, 0.743_150_2, 0.912_029_8];

/// Stage B, for the bass synth: 9 coefficients, transition 0.0406.
/// Stopband about -112 dB, flat to 22 kHz.
/// Generated by `design(9, 0.040_644_725_607_262)`.
const COEFS_B: [f32; 9] = [
    0.032_414_217, 0.121_916_308, 0.249_097_94, 0.391_410_52, 0.530_762_65, 0.656_911_94, 0.767_107_5, 0.864_123_2, 0.954_471_23,
];

/// Coefficients for a polyphase IIR half-band with `n` allpass sections and the given
/// transition bandwidth (fraction of the oversampled rate). Elliptic design.
pub fn design(n: usize, transition: f64) -> Vec<f64> {
    use std::f64::consts::PI;
    let mut k = ((1.0 - transition * 2.0) * PI / 4.0).tan();
    k *= k;
    let kksqrt = (1.0 - k * k).powf(0.25);
    let e = 0.5 * (1.0 - kksqrt) / (1.0 + kksqrt);
    let e2 = e * e;
    let e4 = e2 * e2;
    let q = e * (1.0 + e4 * (2.0 + e4 * (15.0 + 150.0 * e4)));
    let order = (n * 2 + 1) as f64;
    (1..=n)
        .map(|c| {
            let c = c as f64;
            let mut num = 0.0;
            let (mut i, mut j) = (0i32, 1.0);
            loop {
                let t = q.powi(i * (i + 1)) * (((i * 2 + 1) as f64) * c * PI / order).sin() * j;
                num += t;
                i += 1;
                j = -j;
                if t.abs() <= 1e-100 {
                    break;
                }
            }
            let mut den = 0.0;
            let (mut i, mut j) = (1i32, -1.0);
            loop {
                let t = q.powi(i * i) * ((i * 2) as f64 * c * PI / order).cos() * j;
                den += t;
                i += 1;
                j = -j;
                if t.abs() <= 1e-100 {
                    break;
                }
            }
            let ww = num * q.powf(0.25) / (den + 0.5);
            let wwsq = ww * ww;
            let x = ((1.0 - wwsq * k) * (1.0 - wwsq / k)).sqrt() / (1.0 + wwsq);
            (1.0 - x) / (1.0 + x)
        })
        .collect()
}

/// The two allpass chains. Even coefficients filter the first sample of a pair,
/// odd ones the second. Each section is (c + z^-1) / (1 + c z^-1) at the base rate.
#[derive(Clone, Copy)]
struct Chains<const N: usize> {
    c: [f32; N],
    x: [f32; N],
    y: [f32; N],
}

impl<const N: usize> Chains<N> {
    const fn new(c: [f32; N]) -> Self {
        Chains { c, x: [0.0; N], y: [0.0; N] }
    }

    #[inline]
    fn run(&mut self, mut s0: f32, mut s1: f32) -> (f32, f32) {
        let mut i = 0;
        while i + 1 < N {
            let t0 = (s0 - self.y[i]) * self.c[i] + self.x[i];
            let t1 = (s1 - self.y[i + 1]) * self.c[i + 1] + self.x[i + 1];
            self.x[i] = s0;
            self.x[i + 1] = s1;
            self.y[i] = flush_denormal(t0);
            self.y[i + 1] = flush_denormal(t1);
            s0 = t0;
            s1 = t1;
            i += 2;
        }
        if i < N {
            let t0 = (s0 - self.y[i]) * self.c[i] + self.x[i];
            self.x[i] = s0;
            self.y[i] = flush_denormal(t0);
            s0 = t0;
        }
        (s0, s1)
    }
}

/// Two oversampled samples in, one at the base rate out.
#[derive(Clone, Copy)]
pub struct Decim<const N: usize> {
    ch: Chains<N>,
}

/// The decimator every saturator uses (delay 1.5).
pub type Decimator2x = Decim<6>;
/// The bass synth's decimator (delay 2.0, deeper stopband for the oscillators).
pub type BassDecimator = Decim<9>;

impl Decim<6> {
    pub const fn new() -> Self {
        Decim { ch: Chains::new(COEFS_A) }
    }
}

impl Decim<9> {
    pub const fn new() -> Self {
        Decim { ch: Chains::new(COEFS_B) }
    }
}

impl<const N: usize> Decim<N> {
    /// `a` is the earlier oversampled sample, `b` the later one.
    #[inline]
    pub fn process(&mut self, a: f32, b: f32) -> f32 {
        let (p0, p1) = self.ch.run(b, a);
        0.5 * (p0 + p1)
    }
}

impl Default for Decim<6> {
    fn default() -> Self {
        Self::new()
    }
}

impl Default for Decim<9> {
    fn default() -> Self {
        Self::new()
    }
}

/// Upsampler for processing an existing signal at 2x (used by the drive stage).
#[derive(Clone, Copy)]
pub struct Interpolator2x {
    ch: Chains<6>,
}

impl Interpolator2x {
    pub const fn new() -> Self {
        Interpolator2x { ch: Chains::new(COEFS_A) }
    }

    /// One base-rate sample in, two oversampled out (earlier first).
    #[inline]
    pub fn process(&mut self, x: f32) -> (f32, f32) {
        self.ch.run(x, x)
    }
}

impl Default for Interpolator2x {
    fn default() -> Self {
        Self::new()
    }
}

/// Saturator that runs at 2x so its harmonics do not fold back.
///
/// The signal always goes through the 2x path, so the delay is the same with the
/// knob at zero as at full: no timing or phase jump when you touch it.
#[derive(Clone, Copy, Default)]
pub struct Drive {
    up: Interpolator2x,
    down: Decimator2x,
    shape: super::Adaa,
}

impl Drive {
    pub const fn new() -> Self {
        Drive { up: Interpolator2x::new(), down: Decimator2x::new(), shape: super::Adaa::new() }
    }

    /// `amount` 0..1.
    #[inline]
    pub fn process(&mut self, x: f32, amount: f32) -> f32 {
        let (a, b) = self.up.process(x);
        if amount <= 0.001 {
            return self.down.process(a, b);
        }
        let gain = 1.0 + amount * amount * 24.0;
        // Level-matched: turning drive up adds harmonics, not volume.
        let makeup = 0.25 / super::sat(gain * 0.25);
        // Anti-aliased: on top of the 2x oversampling, so the harmonics drive adds above the
        // band fold back far quieter (measured in tests/sound.rs).
        let a = self.shape.process(a * gain) * makeup;
        let b = self.shape.process(b * gain) * makeup;
        self.down.process(a, b)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::dsp::osc::Sine;

    /// Group delay at DC = the first moment of the impulse response.
    fn centroid(h: &[f32]) -> f64 {
        let s: f64 = h.iter().map(|v| *v as f64).sum();
        let m: f64 = h.iter().enumerate().map(|(i, v)| i as f64 * *v as f64).sum();
        m / s
    }

    #[test]
    fn tables_match_the_design() {
        for (got, want) in COEFS_A.iter().zip(design(6, 0.0625)) {
            assert!((*got as f64 - want).abs() < 2e-6, "A {got} vs {want}");
        }
        for (got, want) in COEFS_B.iter().zip(design(9, 0.040_644_725_607_262)) {
            assert!((*got as f64 - want).abs() < 2e-6, "B {got} vs {want}");
        }
    }

    #[test]
    fn decimator_passes_dc_and_removes_top_band() {
        let mut d = Decimator2x::new();
        let mut y = 0.0;
        for _ in 0..400 {
            y = d.process(1.0, 1.0);
        }
        assert!((y - 1.0).abs() < 1e-4, "dc gain {y}");

        // A tone at 0.8 of the oversampled Nyquist (above the base Nyquist) must vanish.
        for f_rel in [0.3, 0.4, 0.47] {
            let sr2 = 96_000.0;
            let mut s = Sine::default();
            let f = f_rel * sr2;
            let mut d = Decimator2x::new();
            let mut peak = 0.0f32;
            for i in 0..8000 {
                let a = s.next(f / sr2);
                let b = s.next(f / sr2);
                let y = d.process(a, b);
                if i > 400 {
                    peak = peak.max(y.abs());
                }
            }
            assert!(peak < 1e-4, "stopband leak {peak} at {f_rel}");
        }
    }

    #[test]
    fn passband_is_flat_to_20k() {
        // Through a whole Drive at 48 kHz: a 20 kHz tone keeps its level.
        let sr = 48_000.0;
        for hz in [100.0, 5_000.0, 15_000.0, 20_000.0] {
            let mut d = Drive::new();
            let mut s = Sine::default();
            let mut peak = 0.0f32;
            for i in 0..20_000 {
                let y = d.process(s.next(hz / sr), 0.0);
                if i > 2000 {
                    peak = peak.max(y.abs());
                }
            }
            assert!((peak - 1.0).abs() < 0.01, "{hz} Hz: {peak}");
        }
    }

    #[test]
    fn delays_are_what_the_engine_compensates() {
        // Drive: up then down, 3 samples.
        let mut d = Drive::new();
        let h: Vec<f32> = (0..400).map(|i| d.process(if i == 0 { 1.0 } else { 0.0 }, 0.0)).collect();
        let c = centroid(&h);
        assert!((c - DRIVE_DELAY).abs() < 0.02, "drive delay {c}");

        // Bass decimator. Impulses on both samples of a pair: the input's centre is a
        // quarter of a base sample in.
        let mut b = BassDecimator::new();
        let h: Vec<f32> = (0..400).map(|i| b.process(if i == 0 { 1.0 } else { 0.0 }, 0.0)).collect();
        let hb: Vec<f32> = {
            let mut b = BassDecimator::new();
            (0..400).map(|i| b.process(0.0, if i == 0 { 1.0 } else { 0.0 })).collect()
        };
        let both: Vec<f32> = h.iter().zip(&hb).map(|(a, b)| a + b).collect();
        let c = centroid(&both) - 0.25;
        assert!((c - BASS_DECIM_DELAY).abs() < 0.02, "bass decimator delay {c}");
    }

    #[test]
    fn drive_stays_level_matched() {
        let sr = 48_000.0;
        let mut s = Sine::default();
        let mut d = Drive::new();
        let mut peak = 0.0f32;
        for i in 0..9600 {
            let y = d.process(s.next(110.0 / sr) * 0.25, 1.0);
            if i > 1000 {
                peak = peak.max(y.abs());
            }
        }
        assert!(peak > 0.2 && peak < 0.3, "{peak}");
    }
}
